"""Command-line entrypoint for generation, validation, and offline sweeps."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from agent.retrieval.corpus import PublishedCorpus

from blogeval.datasets import (
    DatasetError,
    generate_known_item_alias_queryset,
    load_queryset,
    validate_queryset_corpus,
    write_queryset,
)
from blogeval.jsonio import canonical_json_bytes
from blogeval.publication import verify_publication_candidate
from blogeval.runner import (
    EvaluationError,
    run_evaluation,
    verify_run_directory,
    write_run_artifacts,
)

DEFAULT_METHODS = (
    "bm25",
    "bm25-field-weighted",
    "char-ngram",
    "rrf-bm25-char-ngram",
)
DEFAULT_CUTOFFS = (1, 5, 10)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    generate = subparsers.add_parser(
        "generate-known-item",
        help="generate or check alias-derived known-item qrels",
    )
    generate.add_argument("--index-root", type=Path, required=True)
    generate.add_argument("--content-tree-sha", required=True)
    generate.add_argument("--output", type=Path, required=True)
    generate.add_argument(
        "--check",
        action="store_true",
        help="compare canonical generated bytes without writing",
    )

    validate = subparsers.add_parser(
        "validate",
        help="validate a query-set against a verified generated corpus",
    )
    validate.add_argument("--index-root", type=Path, required=True)
    validate.add_argument("--content-tree-sha", required=True)
    validate.add_argument("--dataset", type=Path, required=True)

    sweep = subparsers.add_parser(
        "sweep",
        help="run a deterministic no-provider-cost retrieval sweep",
    )
    sweep.add_argument("--index-root", type=Path, required=True)
    sweep.add_argument("--content-tree-sha", required=True)
    sweep.add_argument("--dataset", type=Path, required=True)
    sweep.add_argument("--output-root", type=Path, default=Path("results"))
    sweep.add_argument("--method", action="append", dest="methods")
    sweep.add_argument("--cutoff", action="append", type=int, dest="cutoffs")
    sweep.add_argument(
        "--require-publishable",
        action="store_true",
        help="always fail locally; publication requires the trusted attestation workflow",
    )

    verify = subparsers.add_parser(
        "verify-run",
        help="regenerate and verify a complete result directory",
    )
    verify.add_argument("--index-root", type=Path, required=True)
    verify.add_argument("--content-tree-sha", required=True)
    verify.add_argument("--dataset", type=Path, required=True)
    verify.add_argument("--run-directory", type=Path, required=True)

    publication = subparsers.add_parser(
        "verify-publication",
        help="require GitHub attestation and verify a publication candidate",
    )
    publication.add_argument("--archive", type=Path, required=True)
    publication.add_argument("--index-root", type=Path, required=True)
    publication.add_argument("--content-tree-sha", required=True)
    publication.add_argument("--dataset", type=Path, required=True)
    publication.add_argument("--expected-commit", required=True)
    publication.add_argument("--workspace-root", type=Path, required=True)
    return parser


def _generate(args: argparse.Namespace) -> int:
    corpus = PublishedCorpus(args.index_root)
    dataset = generate_known_item_alias_queryset(
        corpus,
        content_tree_sha=args.content_tree_sha,
    )
    expected = canonical_json_bytes(dataset.as_dict())
    if args.check:
        try:
            actual = args.output.read_bytes()
        except OSError as exc:
            print(
                f"cannot read committed query-set {args.output}: {exc}", file=sys.stderr
            )
            return 1
        if actual != expected:
            print(
                "committed known-item query-set differs from deterministic generation",
                file=sys.stderr,
            )
            return 1
    else:
        write_queryset(args.output, dataset)
    print(
        json.dumps(
            {
                "checksum": dataset.checksum,
                "dataset_id": dataset.dataset_id,
                "exclusion_count": len(dataset.exclusions),
                "included_occurrence_count": (
                    dataset.provenance.included_occurrence_count
                ),
                "label_status": dataset.labels.status.value,
                "qrel_count": len(dataset.qrels),
                "source_artifacts": [
                    {
                        "path": artifact.path,
                        "sha256": artifact.checksum,
                    }
                    for artifact in dataset.provenance.source_artifacts
                ],
                "source_occurrence_count": (dataset.provenance.source_occurrence_count),
            },
            ensure_ascii=False,
            sort_keys=True,
        )
    )
    return 0


def _validate(args: argparse.Namespace) -> int:
    corpus = PublishedCorpus(args.index_root)
    dataset = load_queryset(args.dataset)
    validate_queryset_corpus(
        dataset,
        corpus,
        content_tree_sha=args.content_tree_sha,
    )
    print(
        json.dumps(
            {
                "checksum": dataset.checksum,
                "dataset_id": dataset.dataset_id,
                "kind": dataset.kind.value,
                "label_status": dataset.labels.status.value,
                "qrel_count": len(dataset.qrels),
                "source_artifacts": [
                    {
                        "path": artifact.path,
                        "sha256": artifact.checksum,
                    }
                    for artifact in dataset.provenance.source_artifacts
                ],
            },
            ensure_ascii=False,
            sort_keys=True,
        )
    )
    return 0


def _sweep(args: argparse.Namespace) -> int:
    corpus = PublishedCorpus(args.index_root)
    dataset = load_queryset(args.dataset)
    methods = tuple(sorted(args.methods or DEFAULT_METHODS))
    cutoffs = tuple(sorted(args.cutoffs or DEFAULT_CUTOFFS))
    run = run_evaluation(
        corpus=corpus,
        dataset=dataset,
        content_tree_sha=args.content_tree_sha,
        method_ids=methods,
        cutoffs=cutoffs,
        require_publishable=args.require_publishable,
    )
    artifacts = write_run_artifacts(
        run,
        corpus=corpus,
        output_root=args.output_root,
    )
    print(
        json.dumps(
            {
                "directory": str(artifacts.directory),
                "method_count": len(run.methods),
                "query_count": len(dataset.qrels),
                "publication_eligible": run.provenance.publication_eligible,
                "result_digest": artifacts.result_digest,
                "run_id": run.run_id,
            },
            ensure_ascii=False,
            sort_keys=True,
        )
    )
    return 0


def _verify_run(args: argparse.Namespace) -> int:
    corpus = PublishedCorpus(args.index_root)
    dataset = load_queryset(args.dataset)
    validate_queryset_corpus(
        dataset,
        corpus,
        content_tree_sha=args.content_tree_sha,
    )
    verified = verify_run_directory(
        args.run_directory,
        corpus=corpus,
        dataset=dataset,
    )
    print(
        json.dumps(
            {
                "result_digest": verified.result_digest,
                "run_id": verified.run.run_id,
            },
            ensure_ascii=False,
            sort_keys=True,
        )
    )
    return 0


def _verify_publication(args: argparse.Namespace) -> int:
    corpus = PublishedCorpus(args.index_root)
    dataset = load_queryset(args.dataset)
    validate_queryset_corpus(
        dataset,
        corpus,
        content_tree_sha=args.content_tree_sha,
    )
    verified = verify_publication_candidate(
        args.archive,
        corpus=corpus,
        dataset=dataset,
        expected_commit=args.expected_commit,
        workspace_root=args.workspace_root,
    )
    print(
        json.dumps(
            {
                "commit_sha": verified.commit_sha,
                "execution_image_digest": verified.execution_image_digest,
                "result_digest": verified.result_digest,
                "run_id": verified.run_id,
                "workflow_run_id": verified.workflow_run_id,
            },
            ensure_ascii=False,
            sort_keys=True,
        )
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        if args.command == "generate-known-item":
            return _generate(args)
        if args.command == "validate":
            return _validate(args)
        if args.command == "sweep":
            return _sweep(args)
        if args.command == "verify-run":
            return _verify_run(args)
        if args.command == "verify-publication":
            return _verify_publication(args)
        raise AssertionError(f"unhandled command: {args.command}")
    except (DatasetError, EvaluationError, OSError, ValueError) as exc:
        print(f"blogeval failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
